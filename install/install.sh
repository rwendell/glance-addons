#!/bin/sh
# Installs the Glance plugin manager and its config scaffold.
# Usage: sh install.sh [config-dir] [ref] [--local]
#
# The config dir defaults to ${XDG_CONFIG_HOME:-$HOME/.config}/glance.
# Set GLANCE_CONFIG to override it.
#
# An existing config dir is moved to <config-dir>.bak before the new scaffold
# is written. plugins.json, pages/, and assets/ are copied into the new config.
#
# The manager loads from jsDelivr by default. Pass --local (or set
# GLANCE_PLUGINS_LOCAL=1) to download a copy into assets/ instead.

set -eu

CONFIG=""
REF=""
LOCAL=0
BACKUP=""
MOVED_MANAGER=""
MARKER="# Generated by the glance-addons installer."
LEGACY_MARKER="# Generated by the glance-plugins installer."

if [ "${GLANCE_PLUGINS_LOCAL:-0}" = "1" ]; then
    LOCAL=1
fi

for arg in "$@"; do
    case "$arg" in
        --local)
            LOCAL=1
            ;;
        --remote)
            LOCAL=0
            ;;
        --help | -h)
            printf 'Usage: sh install.sh [config-dir] [ref] [--local]\n'
            exit 0
            ;;
        -*)
            printf 'Unknown option: %s\n' "$arg" >&2
            exit 1
            ;;
        *)
            if [ -z "$CONFIG" ]; then
                CONFIG="$arg"
            elif [ -z "$REF" ]; then
                REF="$arg"
            else
                printf 'Too many arguments.\n' >&2
                exit 1
            fi
            ;;
    esac
done

CONFIG="${CONFIG:-${GLANCE_CONFIG:-${XDG_CONFIG_HOME:-$HOME/.config}/glance}}"
REF="${REF:-${GLANCE_PLUGINS_REF:-main}}"
RAW="https://raw.githubusercontent.com/rwendell/glance-addons/$REF"
REMOTE_URL="https://cdn.jsdelivr.net/gh/rwendell/glance-addons@$REF/plugins/plugin-manager/dist/plugin-manager.js"

CONFIG_PARENT="$(dirname "$CONFIG")"
CONFIG_NAME="$(basename "$CONFIG")"
mkdir -p "$CONFIG_PARENT"
CONFIG="$(cd "$CONFIG_PARENT" && pwd)/$CONFIG_NAME"

ASSETS="$CONFIG/assets"
PAGES="$CONFIG/pages"
GLANCE="$CONFIG/glance.yml"
HOME_PAGE="$PAGES/home.yml"
PLUGINS="$CONFIG/plugins.json"
SERVED="$ASSETS/plugins.json"
TARGET="$ASSETS/plugin-manager.js"

download() {
    URL="$1"
    OUT="$2"

    if command -v curl >/dev/null 2>&1; then
        curl -fsSL "$URL" -o "$OUT"
    elif command -v wget >/dev/null 2>&1; then
        wget -qO "$OUT" "$URL"
    else
        echo "curl or wget is required." >&2
        exit 1
    fi
}

yaml_quote() {
    printf "'%s'" "$(printf '%s' "$1" | sed "s/'/''/g")"
}

backup_path() {
    SOURCE="$1"
    DESTINATION="$SOURCE.bak"
    N=1

    while [ -e "$DESTINATION" ] || [ -L "$DESTINATION" ]; do
        DESTINATION="$SOURCE.bak.$N"
        N=$((N + 1))
    done

    printf '%s' "$DESTINATION"
}

GENERATED=0

if [ -f "$GLANCE" ] &&
    { grep -qF "$MARKER" "$GLANCE" || grep -qF "$LEGACY_MARKER" "$GLANCE"; }; then
    GENERATED=1
fi

if [ "$GENERATED" -eq 0 ] &&
    { [ -L "$CONFIG" ] || [ -n "$(ls -A "$CONFIG" 2>/dev/null)" ]; }; then
    BACKUP="$(backup_path "$CONFIG")"
    mv "$CONFIG" "$BACKUP"
    echo "Backed up existing config to $BACKUP"
fi

mkdir -p "$ASSETS/themes" "$PAGES"

if [ -n "$BACKUP" ]; then
    if [ -d "$BACKUP/assets" ]; then
        cp -R "$BACKUP/assets/." "$ASSETS/"
        rm -f "$ASSETS/plugin-manager.js" "$ASSETS"/plugin-manager.js.bak*
        rm -f "$ASSETS/plugins.json"
    fi

    if [ -d "$BACKUP/pages" ]; then
        cp -R "$BACKUP/pages/." "$PAGES/"
    fi

    if [ -f "$BACKUP/plugins.json" ]; then
        cp "$BACKUP/plugins.json" "$PLUGINS"
    elif [ -f "$BACKUP/assets/plugins.json" ]; then
        cp "$BACKUP/assets/plugins.json" "$PLUGINS"
    fi
fi

if [ "$LOCAL" -eq 1 ]; then
    SCRIPT_SRC="/assets/plugin-manager.js"
    echo "Downloading plugin-manager ($REF)..."
    download "$RAW/plugins/plugin-manager/dist/plugin-manager.js" "$TARGET"
else
    SCRIPT_SRC="$REMOTE_URL"

    if [ -e "$TARGET" ] || [ -L "$TARGET" ]; then
        MOVED_MANAGER="$(backup_path "$TARGET")"
        mv "$TARGET" "$MOVED_MANAGER"
        echo "Moved local manager to $MOVED_MANAGER"
    fi
fi

if [ ! -f "$PLUGINS" ]; then
    if [ -f "$SERVED" ] && [ ! -L "$SERVED" ]; then
        mv "$SERVED" "$PLUGINS"
        echo "Moved $SERVED to $PLUGINS"
    else
        printf '{\n  "plugins": []\n}\n' > "$PLUGINS"
        echo "Created $PLUGINS"
    fi
fi

if [ -L "$SERVED" ]; then
    if [ ! -e "$SERVED" ]; then
        ln -sfn "../plugins.json" "$SERVED"
        echo "Repaired $SERVED"
    fi
elif [ -e "$SERVED" ]; then
    echo "$SERVED is not a symlink; leaving it alone." >&2
else
    ln -s "../plugins.json" "$SERVED"
    echo "Linked $SERVED -> ../plugins.json"
fi

HAVE_PAGES=0

for PAGE in "$PAGES"/*.yml; do
    if [ -e "$PAGE" ]; then
        HAVE_PAGES=1
        break
    fi
done

if [ "$HAVE_PAGES" -eq 0 ]; then
    {
        printf '%s\n' "$MARKER"
        printf '# One page. Add more files under pages/ and include them from glance.yml.\n'
        printf -- '- name: Home\n'
        printf '  columns:\n'
        printf '    - size: full\n'
        printf '      widgets:\n'
        printf '        - type: search\n'
        printf '          hide-header: true\n'
        printf '          autofocus: true\n'
    } > "$HOME_PAGE"
    echo "Created $HOME_PAGE"
fi

if [ "$GENERATED" -eq 1 ]; then
    echo "Keeping existing $GLANCE"

    if ! grep -qF "$SCRIPT_SRC" "$GLANCE"; then
        printf '\nNote: %s does not contain the current manager URL:\n' "$GLANCE"
        printf '  %s\n' "$SCRIPT_SRC"
        printf 'Update its <script> tag or remove the file and rerun.\n'
    fi
else
    {
        printf '%s\n' "$MARKER"
        printf '# Add pages with: - $include: pages/[name].yml\n'
        printf '# Move theme, branding, auth, and other top-level settings here.\n'
        printf '\n'
        printf 'server:\n'
        printf '  assets-path: %s\n' "$(yaml_quote "$ASSETS")"
        printf '\n'
        printf 'document:\n'
        printf '  head: |\n'
        printf '    <script src="%s"></script>\n' "$SCRIPT_SRC"
        printf '\n'
        printf 'pages:\n'

        if [ -f "$HOME_PAGE" ]; then
            printf '  - $include: pages/home.yml\n'
        fi

        for PAGE in "$PAGES"/*.yml; do
            [ -e "$PAGE" ] || continue
            [ "$PAGE" = "$HOME_PAGE" ] && continue
            printf '  - $include: pages/%s\n' "$(basename "$PAGE")"
        done
    } > "$GLANCE"

    echo "Created $GLANCE"
fi

printf '\n'
if [ "$LOCAL" -eq 1 ]; then
    printf 'Plugin manager installed locally at %s\n' "$TARGET"
else
    printf 'Plugin manager loads from %s\n' "$REMOTE_URL"
fi
printf 'Plugin config: %s\n' "$PLUGINS"
printf 'Glance entry point: %s\n' "$GLANCE"
printf 'Pages: %s\n' "$PAGES"

if [ -n "$BACKUP" ]; then
    printf '\n'
    printf 'Your previous config was moved to:\n  %s\n' "$BACKUP"
    printf 'The new config kept plugins.json, pages/, and assets/ from the backup.\n'
    printf 'Move any page definitions still in the backup glance.yml into pages/,\n'
    printf 'copy theme, branding, auth, and other settings into %s,\n' "$GLANCE"
    printf 'and copy any other files you need from the backup.\n'
fi

printf '\nEdit %s to add plugins.\n' "$PLUGINS"
